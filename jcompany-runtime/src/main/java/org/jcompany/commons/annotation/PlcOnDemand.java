package org.jcompany.commons.annotation;

import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * Indica, em classes de Mestre, que seus detalhes deverão ser recuperados "on-demand" (por demanda).
 * Difere do Lazy no sentido em que o detalhe, ao ser recuperado e ação subsequente, nem tente instanciar seu Mestre.
 * @since jCompany 3.1
 */
@Retention(RetentionPolicy.RUNTIME)
@Target(ElementType.FIELD)
public @interface PlcOnDemand {}
