package org.jcompany.config.domain;

/**
 * Convenções para definição de classes descendentes
 */
public class PlcConfigDescendentConvention {


	/**
	 * Define a classe decendente 
	 */
	private Class clazz;

	public Class getClazz() {
		return clazz;
	}

	public void setClazz(Class clazz) {
		this.clazz = clazz;
	}
}
